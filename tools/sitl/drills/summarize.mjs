#!/usr/bin/env node
// Turns run-drills.mjs's results.json into a markdown summary (pass counts per scenario and the
// min-max of every measured value across runs).
//   node tools/sitl/drills/summarize.mjs [docs/sim/drills/results.json] > docs/sim/drills/summary.md
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../../..");
const file = process.argv[2] ?? join(ROOT, "docs/sim/drills/results.json");
const data = JSON.parse(readFileSync(file, "utf8"));

const order = [];
const byId = new Map();
for (const r of data.results) {
  if (!byId.has(r.id)) {
    byId.set(r.id, []);
    order.push(r.id);
  }
  byId.get(r.id).push(r);
}

const numberOf = (value) => {
  if (typeof value === "number") return value;
  if (typeof value === "string") {
    const m = /^-?\d+(\.\d+)?/.exec(value);
    if (m) return Number(m[0]);
  }
  return null;
};

const cell = (s) => String(s).replace(/\|/g, "\\|");
const lines = [
  `# Flight-control SITL drill results`,
  ``,
  `Generated by \`tools/sitl/drills/summarize.mjs\` from \`results.json\` (${data.runs} runs per scenario, Betaflight 2026.6.2 SITL). Method, pass criteria and findings: [\`../flight-control-drills.md\`](../flight-control-drills.md).`,
  ``,
  `| # | Scenario | Passed | Measurement | Min | Max | Limit |`,
  `| --- | --- | --- | --- | --- | --- | --- |`,
];

for (const id of order) {
  const runs = byId.get(id);
  const ran = runs.filter((r) => !r.skipped);
  const passed = ran.filter((r) => r.pass).length;
  const name = runs[0].name;
  const passText = ran.length === 0 ? `skipped: ${runs[0].skipped}` : `${passed}/${ran.length}`;
  const checks = new Map();
  for (const r of ran) {
    for (const c of r.checks ?? []) {
      if (!checks.has(c.name)) checks.set(c.name, { values: [], limit: c.limit, failed: 0 });
      const entry = checks.get(c.name);
      entry.values.push(c.value);
      if (!c.pass) entry.failed++;
    }
  }
  let first = true;
  for (const [checkName, entry] of checks) {
    const nums = entry.values.map(numberOf).filter((v) => v !== null);
    const allNumeric = nums.length === entry.values.length && nums.length > 0;
    const min = allNumeric ? Math.min(...nums) : [...new Set(entry.values.map((v) => (typeof v === "string" ? v : JSON.stringify(v))))].slice(0, 2).join(", ");
    const max = allNumeric ? Math.max(...nums) : "";
    const label = entry.failed ? `${checkName} (failed ${entry.failed}x)` : checkName;
    lines.push(`| ${first ? id : ""} | ${first ? cell(name) : ""} | ${first ? passText : ""} | ${cell(label)} | ${cell(min)} | ${cell(max)} | ${cell(entry.limit ?? "")} |`);
    first = false;
  }
  if (first) lines.push(`| ${id} | ${cell(name)} | ${passText} | | | | |`);
}

process.stdout.write(lines.join("\n") + "\n");
